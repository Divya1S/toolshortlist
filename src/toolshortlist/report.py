"""Render the result tables from the JSON files in results/.

Writes results/baselines.md and results/data_audit.md. Every number in them is
read from a JSON file that a script produced; nothing is typed by hand.

Run: uv run python -m toolshortlist.report
"""

import json
import tomllib
from pathlib import Path

BASELINES = [
    "bm25",
    "all-MiniLM-L6-v2", "bge-small-en-v1.5", "bge-base-en-v1.5",
    "rrf-bm25-all-MiniLM-L6-v2", "rrf-bm25-bge-small-en-v1.5", "rrf-bm25-bge-base-en-v1.5",
]
# (label, untrained run, trained run, setting): the ToolRet authors' checkpoint against its base, like for like.
TRAINED_PAIRS = [
    ("query alone", "paper-bge-base-en-v1.5", "paper-toolret-trained-bge-base", "query"),
    ("query alone, with the released code's empty 'Instruct:' prefix",
     "paper-codeprefix-bge-base-en-v1.5", "paper-codeprefix-toolret-trained-bge-base", "query"),
    ("with instruction", "paper-bge-base-en-v1.5", "paper-toolret-trained-bge-base", "instruction"),
]
CATEGORIES = ["web", "code", "customized"]
TOLERANCE = 0.5  # nDCG@10 points; fixed before the reproduction runs
HEADER = "Generated by `python -m toolshortlist.report` from the JSON files in this directory. Do not edit by hand."


def pct(value: float) -> str:
    return f"{100 * value:.2f}"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def load_results(directory: Path) -> dict:
    results = {}
    for path in sorted(directory.glob("*.json")):
        data = json.loads(path.read_text())
        if isinstance(data, dict) and "benchmarks" in data:
            results[data["name"]] = data
    return results


def split(result: dict, setting: str, name: str) -> dict:
    return result["benchmarks"]["toolret"]["settings"][setting]["splits"][name]


def category_mean(result: dict, setting: str, metric: str = "ndcg@10") -> tuple[list[float], float]:
    """The ToolRet paper's aggregation: mean over tasks within each category, then over categories."""
    per_category = [split(result, setting, c)["group_mean"][metric] for c in CATEGORIES]
    return per_category, sum(per_category) / len(per_category)


def baseline_table(results: dict, setting: str) -> str:
    rows = []
    for name in BASELINES:
        if name not in results:
            continue
        unseen = split(results[name], setting, "unseen_source")["query_mean"]
        seen = split(results[name], setting, "seen_source")["query_mean"]
        row = [name] + [pct(unseen[m]) for m in ("recall@1", "recall@5", "recall@10", "ndcg@10", "completeness@10")]
        row.append(pct(seen["ndcg@10"]))
        live = results[name]["benchmarks"].get("livemcpbench", {}).get("settings", {}).get(setting)
        if setting == "query" and live:
            for metric in ("recall@5", "ndcg@10"):
                low, high = live["all"]["ci95"][metric]
                row.append(f"{pct(live['all']['query_mean'][metric])} ({pct(low)}–{pct(high)})")
        rows.append(row)
    header = ["Retriever", "Unseen R@1", "Unseen R@5", "Unseen R@10", "Unseen nDCG@10", "Unseen C@10",
              "Seen nDCG@10"]
    if setting == "query":
        header += ["LiveMCPBench R@5 (95% CI)", "LiveMCPBench nDCG@10 (95% CI)"]
    return table(header, rows)


def task_mean_table(results: dict) -> str:
    rows = []
    for name in BASELINES:
        if name in results:
            unseen = split(results[name], "query", "unseen_source")["group_mean"]
            rows.append([name] + [pct(unseen[m]) for m in ("recall@10", "ndcg@10", "completeness@10")])
    return table(["Retriever", "Unseen R@10", "Unseen nDCG@10", "Unseen C@10"], rows)


def reproduction_table(results: dict, published: list[dict]) -> str:
    rows = []
    for row in published:
        if row["run"] not in results:
            continue
        ours, ours_average = category_mean(results[row["run"]], row["setting"])
        difference = 100 * ours_average - row["average"]
        rows.append([
            row["label"], "query alone" if row["setting"] == "query" else "with instruction", row["source"],
            f"{row['average']:.2f}", pct(ours_average), f"{difference:+.2f}",
            "yes" if abs(difference) <= TOLERANCE else "no",
            " / ".join(f"{row[c]:.2f}" for c in CATEGORIES), " / ".join(pct(v) for v in ours),
        ])
    return table(["Model", "Our setting", "Paper", "Published", "Ours", "Difference",
                  f"Within {TOLERANCE}", "Published web / code / customized", "Ours web / code / customized"], rows)


def trained_table(results: dict) -> str:
    rows = []
    for label, base_run, trained_run, setting in TRAINED_PAIRS:
        if base_run not in results or trained_run not in results:
            continue
        for part in ("unseen_source", "seen_source"):
            base = split(results[base_run], setting, part)
            trained = split(results[trained_run], setting, part)
            row = [label, part.replace("_", "-"), str(base["queries"])]
            for metric in ("ndcg@10", "recall@10"):
                before, after = base["query_mean"][metric], trained["query_mean"][metric]
                row += [pct(before), pct(after), f"{100 * (after - before):+.2f}"]
            rows.append(row)
    return table(["Query format", "Tasks", "Queries", "nDCG@10 base", "nDCG@10 trained", "Gain",
                  "R@10 base", "R@10 trained", "Gain"], rows)


TRAIN_CONFIGS = ["default", "base-minilm", "base-bge-base", "text-name-description", "text-name", "no-hard-negatives"]
REFERENCE_RUNS = ["bm25", "all-MiniLM-L6-v2", "bge-small-en-v1.5", "bge-base-en-v1.5", "rrf-bm25-bge-small-en-v1.5"]


def mean_sd(values: list[float]) -> str:
    """Mean over seeds, with the sample standard deviation when there is more than one seed."""
    m = sum(values) / len(values)
    if len(values) < 2:
        return pct(m)
    sd = (sum((v - m) ** 2 for v in values) / (len(values) - 1)) ** 0.5
    return f"{pct(m)} ± {pct(sd)}"


def ablation_table(results: dict) -> str:
    """Trained runs grouped by config, mean ± sd over seeds, with the untrained references below."""
    def cells(runs):
        unseen = [split(r, "query", "unseen_source")["query_mean"] for r in runs]
        seen = [split(r, "query", "seen_source")["query_mean"] for r in runs]
        live = [r["benchmarks"]["livemcpbench"]["settings"]["query"]["all"]["query_mean"] for r in runs]
        return [mean_sd([u["ndcg@10"] for u in unseen]), mean_sd([u["recall@10"] for u in unseen]),
                mean_sd([u["completeness@10"] for u in unseen]), mean_sd([s["ndcg@10"] for s in seen]),
                mean_sd([l["recall@5"] for l in live]), mean_sd([l["ndcg@10"] for l in live])]
    rows = []
    for config in TRAIN_CONFIGS:
        runs = [r for r in results.values() if (r.get("config") or {}).get("train", {}).get("config") == config]
        if not runs:
            continue
        train = runs[0]["config"]["train"]
        rows.append([f"trained: {config}", train["base"].split("/")[-1], train["text_mode"],
                     "on" if train["hard_negatives"] else "off", str(len(runs))] + cells(runs))
    for name in REFERENCE_RUNS:
        if name in results:
            rows.append([f"untrained: {name}", "", "", "", ""] + cells([results[name]]))
    return table(["Run", "Base model", "Tool text", "Hard negatives", "Seeds", "Unseen nDCG@10", "Unseen R@10",
                  "Unseen C@10", "Seen nDCG@10", "LiveMCPBench R@5", "LiveMCPBench nDCG@10"], rows)


def render_baselines(directory: Path) -> str:
    results = load_results(directory)
    published = tomllib.loads(Path("configs/published.toml").read_text())["row"]
    any_result = next(iter(results.values()))
    unseen, seen = (split(any_result, "query", s) for s in ("unseen_source", "seen_source"))
    live = any_result["benchmarks"]["livemcpbench"]
    parts = [
        "# Stage 1 results: baselines", HEADER,
        "All scores are multiplied by 100. R@k is Recall@k and C@10 is Completeness@10.",
        f"ToolRet queries are searched against the whole corpus of {any_result['benchmarks']['toolret']['tools']:,} tools. "
        f"Unseen-source tasks ({unseen['groups']} tasks, {unseen['queries']:,} queries) share no source with ToolRet's "
        f"training set; seen-source tasks ({seen['groups']} tasks, {seen['queries']:,} queries) do. "
        "The split comes from [data_audit.md](data_audit.md). "
        f"LiveMCPBench has {live['queries']} queries over {live['tools']} tools, and its labels follow this project's "
        "own protocol (see DATA.md).",
        "## 1. Baselines, query alone (the primary setting)",
        "Mean over queries. Each off-the-shelf model is used as its model card recommends.",
        baseline_table(results, "query"),
        "## 2. Unseen-source ToolRet, mean over tasks",
        "The same runs with every task weighted equally, so large tasks do not dominate.",
        task_mean_table(results),
        "## 3. Baselines, query plus ToolRet's instruction (secondary)",
        "ToolRet's instructions were written by an LLM that was shown the gold tools, so this setting "
        "gives the retriever information a deployed system does not have. It is here only for comparison "
        "with published numbers.",
        baseline_table(results, "instruction"),
        "## 4. Reproduction of published ToolRet numbers",
        "nDCG@10 under the paper's protocol and its aggregation: the mean over tasks within each category, "
        "then the mean of the three categories. Published numbers are from the ToolRet paper "
        "(arXiv 2503.01763v2) and are listed in `configs/published.toml`. "
        "The paper does not say which setting its trained models were evaluated in, so the trained "
        "checkpoint is compared in both.",
        reproduction_table(results, published),
    ]
    if any(base in results and trained in results for _, base, trained, _ in TRAINED_PAIRS):
        parts += [
            "## 5. Where the ToolRet authors' trained checkpoint gains",
            "`bge-base-en-v1.5` before and after the ToolRet authors fine-tuned it on their training set, "
            "compared like for like under three query formats. The checkpoint was trained on queries in the "
            "`Instruct: ... Query: ...` template, so the format matters for it. Mean over queries.",
            trained_table(results),
        ]
    if any((r.get("config") or {}).get("train") for r in results.values()):
        parts += [
            "## 6. Trained models (Stage 2)",
            "Each row is one training config; seeds are averaged and the spread is the sample standard "
            "deviation. Every ablation changes one thing from `default`. The untrained references are the "
            "Stage 1 baselines from section 1. Query alone, mean over queries.",
            ablation_table(results),
        ]
    return "\n\n".join(parts) + "\n"


def render_audit(directory: Path) -> str:
    audit = json.loads((directory / "data_audit.json").read_text())
    tasks, totals = audit["tasks"], audit["totals"]
    columns = ["queries", "queries_duplicating_a_training_query", "queries_identical_to_a_training_query",
               "queries_with_a_gold_tool_in_training", "queries_with_every_gold_tool_in_training"]
    rows = [[f"`{task}`"] + [f"{tasks[task].get(c, 0):,}" for c in columns] + ["; ".join(tasks[task]["reasons"])]
            for task in audit["seen_source_tasks"]]
    unseen = audit["unseen_source_tasks"]
    rows.append([f"The {len(unseen)} unseen-source tasks"]
                + [f"{sum(tasks[t].get(c, 0) for t in unseen):,}" for c in columns] + [""])
    rows.append(["All tasks"] + [f"{totals.get(c, 0):,}" for c in columns] + [""])
    criteria = [[key.removeprefix("gold tools: "), f"{value:,}"]
                for key, value in sorted(totals.items()) if key.startswith("gold tools: ")]
    thresholds = audit["thresholds"]
    parts = [
        "# Overlap between ToolRet's training set and its evaluation set", HEADER,
        "Produced by `python -m toolshortlist.audit`.",
        "## Rule", audit["rule"],
        f"A query duplicates a training query if the two are identical after normalisation, or their word sets "
        f"have a Jaccard overlap of at least {thresholds['query_jaccard']}. A gold tool matches a training positive "
        f"under any of the four criteria in the last table; descriptions are near-identical at a difflib ratio of "
        f"at least {thresholds['description_ratio']}, and an identical description counts on its own only if it has "
        f"at least {thresholds['min_description_chars']} characters. These thresholds were fixed before the counts "
        "were seen.",
        "## Per task",
        table(["Task", "Queries", "Duplicate a training query", "of which identical",
               "Have a gold tool that is a training positive", "Every gold tool is a training positive",
               "Why seen-source"], rows),
        "## Training set",
        table(["", "Count"], [
            ["Training rows", f"{audit['train']['rows']:,}"],
            ["Rows to remove before training (their query duplicates an evaluation query)",
             f"{audit['train']['rows_to_exclude']:,}"],
            ["Distinct tools used as training positives", f"{audit['train']['distinct_positive_tools']:,}"],
            ["Tools in the evaluation corpus", f"{audit['corpus']['tools']:,}"],
            ["of which identical to a training positive", f"{audit['corpus']['identical_to_a_training_positive']:,}"],
            ["of which identical to a training positive or negative",
             f"{audit['corpus']['identical_to_a_training_positive_or_negative']:,}"],
        ]),
        "## How gold tools matched training positives",
        f"Out of {totals['gold_tools']:,} gold-tool labels, {totals['gold_tools_matching_a_training_positive']:,} matched.",
        table(["Criterion", "Gold-tool labels"], criteria),
        "The ids of the training rows to remove are in `train_exclude_ids.json`.",
    ]
    return "\n\n".join(parts) + "\n"


def main(directory: str = "results"):
    directory = Path(directory)
    (directory / "data_audit.md").write_text(render_audit(directory))
    (directory / "baselines.md").write_text(render_baselines(directory))
    print(f"wrote {directory / 'data_audit.md'} and {directory / 'baselines.md'}")


if __name__ == "__main__":
    main()
